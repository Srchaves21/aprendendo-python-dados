turno = input("Digite o turno em que você estuda (Matutino, Vespertino, Noturno): ").upper()

if turno == 'MATUTINO':
    print('Bom dia amiguinho!')
elif turno == 'VESPERTINO':
    print('Boa tarde Marilene')
elif turno == 'NOTURNO':
    print('Boa noite serjão berranteiro')
else:
    print('Digite um turno valido rapariga!!')